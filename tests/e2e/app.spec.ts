for (const width of [360, 768, 1024, 1280]) test(`responsive ${width}px and accessible shell`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 }); await page.goto("/");
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/home-${width}.png`, fullPage: true });
  await page.goto("/question/?id=L001-Q01"); await expect(page.getByRole("heading", { name: "Target Recovery" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const results = await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze();
  expect(results.violations).toEqual([]);
});
test("cached solve route works offline", async ({ page, context }) => {
  await page.goto("/question/?id=L001-Q01");
  await page.evaluate(async () => { await navigator.serviceWorker.ready; });
  await page.reload(); await expect(page.getByRole("heading", { name: "Target Recovery" })).toBeVisible();
  await context.setOffline(true); await page.reload();
  await expect(page.getByRole("heading", { name: "Target Recovery" })).toBeVisible();
  await page.getByLabel(/sisa = tersedia/).check();
  await page.getByRole("button", { name: "Lanjutkan", exact: true }).click();
  await page.getByLabel("Sisa tersedia", { exact: true }).fill("122");
  await page.getByRole("button", { name: "Periksa jawaban" }).click();
  await expect(page.getByText("Checkpoint otomatis benar.")).toBeVisible();
});
